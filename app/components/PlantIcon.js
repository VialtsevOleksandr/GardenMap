const SVG_BY_ID = {
  beet: BEET_SVG,
  radish: RADISH_SVG,
  parsley: PARSLEY_SVG,
};

const NAME_TO_ID = {
  'Буряк': 'beet',
  Beet: 'beet',
  'Редиска': 'radish',
  Radish: 'radish',
  'Петрушка': 'parsley',
  Parsley: 'parsley',
};

function resolvePlantId({ plantId, id, itemId, name }) {
  if (id && SVG_BY_ID[id]) return id;
  if (plantId) return plantId;
  if (itemId && SVG_BY_ID[itemId]) return itemId;
  return NAME_TO_ID[name] || null;
}

export default function PlantIcon({
  plantId,
  id,
  itemId,
  name,
  icon,
  size = 24,
  fallback = '🌱',
  textStyle,
}) {
  const resolvedId = resolvePlantId({ plantId, id, itemId, name });
  const xml = resolvedId ? SVG_BY_ID[resolvedId] : null;

  if (xml) {
    return <SvgXml xml={xml} width={size} height={size} />;
  }

  return <Text style={[{ fontSize: size }, textStyle]}>{icon || fallback}</Text>;
}
